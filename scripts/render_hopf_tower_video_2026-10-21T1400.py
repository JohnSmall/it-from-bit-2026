#!/usr/bin/env python3
"""render_hopf_tower_video_2026-10-21T1400.py

Part two of the Wigner's-friend explainer: the chain of observers mapped onto
the Cayley-Dickson ladder. It animates the figure the paper already specifies
in TikZ in paper1/wigners_friend_in_the_hopf_picture_2026-06-13.tex, and every
claim is taken from Section sec:wf-chain-type, "Where the chain goes next: one
more rung, then copies".

The arithmetic that governs the whole film, quoted from that subsection:

  F's chart of S            S^3  -> S^2,  fibre S^1,  C,  one wire
  W's chart of {S,F}        S^7  -> S^4,  fibre S^3,  H,  two wires
  O_W's chart of {S,F,W}    S^15 -> S^8,  fibre S^7,  O,  three wires  <- last
  the fourth observer       no fibration: the sedenions have zero divisors
                            and admit no S^31 -> S^16

What the fourth wire adds instead is finite. Brown: Aut(S) = G_2 x S_3. The
identity component is unchanged from the octonions; the entire gain is a
component group generated by an order-three automorphism, and that discrete
choice among three is the generation label. The fifth wire and every wire
after it add one more S_3 and nothing else, and the derivation algebra is g_2
from the octonions onward. Notebook T checks it directly:

  dim Der(A_n) = 0, 3, 14, 14, 14   for n = 1..5

So the increments of the tower are, in order, a force, a force, a label, and
then the same finite permutation of copies at every step. The chain is
unbounded in length and bounded in type.

Deliberately NOT claimed here: that each observer gets his own Hopf level
without end. Only three fibrations exist, by Adams; the fourth observer is
where the tower stops supplying them.

No randomness. `--preview N` renders one frame to PNG.
"""
import argparse
from pathlib import Path

import numpy as np
import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt
from matplotlib.animation import FFMpegWriter
from mpl_toolkits.mplot3d import Axes3D  # noqa: F401

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "media" / "hopf_tower_2026-10-21.mp4"
FPS = 30

INK = "#e8e6e3"
DIM = "#8b8782"
BG = "#121316"
FRIEND = "#4fb3d9"
WIGNER = "#e0893b"
ACCENT = "#c45b8c"
DEAD = "#6c6a68"

# the ladder: label, wires, total space, base, fibre, what the rung adds
RUNGS = [
    ("$\\mathbb{C}$", "one wire",    "$S^{3}$",  "$S^{2}$", "$S^{1}$",  "a force"),
    ("$\\mathbb{H}$", "two wires",   "$S^{7}$",  "$S^{4}$", "$S^{3}$",  "a force"),
    ("$\\mathbb{O}$", "three wires", "$S^{15}$", "$S^{8}$", "$S^{7}$",  "a force"),
    ("$\\mathbb{S}$", "four wires",  "$S^{31}$", "---",     "none",     "a label"),
    ("$\\mathbb{T}$", "five wires",  "---",      "---",     "none",     "copies"),
]
WHO = ["$S$", "$F$", "$W$", "$O_{W}$", "$O_{O_{W}}$"]
WHOLONG = ["the system", "the friend", "Wigner",
           "the observer of Wigner", "the observer of that observer"]

SCENES = [("chain", 13), ("staircase", 17), ("promotion", 14),
          ("stop", 16), ("copies", 14), ("punch", 9)]
BOUNDS, _t = [], 0
for _n, _s in SCENES:
    BOUNDS.append((_n, _t, _t + _s * FPS))
    _t += _s * FPS
TOTAL = _t


def ease(x):
    x = np.clip(x, 0.0, 1.0)
    return x * x * (3.0 - 2.0 * x)


def fade(local, n, hold=0.12):
    f = local / n
    return float(min(np.clip(f / hold, 0, 1), np.clip((1 - f) / hold, 0, 1)))


def text(fig, x, y, s, size=20, c=INK, a=1.0, weight="normal", ha="center", style="normal"):
    if a <= 0.01:
        return
    fig.text(x, y, s, color=c, fontsize=size, alpha=a, ha=ha, va="center",
             weight=weight, style=style, family="DejaVu Sans")


def stick(ax, x, y, s, col, alpha):
    """The paper's stick figure: a describer perched on his sealed box."""
    ax.add_patch(plt.Circle((x, y + 0.46 * s), 0.095 * s, fill=False,
                            ec=col, lw=1.6, alpha=alpha))
    ax.plot([x, x], [y + 0.365 * s, y + 0.10 * s], color=col, lw=1.6, alpha=alpha)
    ax.plot([x - 0.13 * s, x, x + 0.13 * s],
            [y + 0.21 * s, y + 0.30 * s, y + 0.21 * s], color=col, lw=1.6, alpha=alpha)
    ax.plot([x - 0.11 * s, x, x + 0.11 * s],
            [y - 0.11 * s, y + 0.10 * s, y - 0.11 * s], color=col, lw=1.6, alpha=alpha)


def gauge_circle(ax, x, y, s, alpha, col=DIM, lift=0.0):
    """His own gauge circle: the phase he cannot see around."""
    ax.add_patch(plt.Circle((x, y + (0.86 + lift) * s), 0.13 * s, fill=False,
                            ec=col, lw=1.5, ls=(0, (3, 3)), alpha=alpha))


def sc_chain(fig, k, n):
    a = fade(k, n, 0.10)
    text(fig, .5, .93, "The chain of observers", 27, ACCENT, a, "bold")
    ax = fig.add_axes([.03, .22, .94, .60]); ax.set_axis_off()
    ax.set_xlim(0, 10.4); ax.set_ylim(0, 3.4)
    for i in range(5):
        s = ease((k - 12 - 34 * i) / 40)
        if s <= 0:
            continue
        x = 1.0 + 2.1 * i
        col = [INK, FRIEND, WIGNER, ACCENT, DEAD][i]
        if i == 0:
            ax.add_patch(plt.Circle((x, 0.95), 0.18, color=col, alpha=.9 * a * s))
        else:
            ax.add_patch(plt.Rectangle((x - .62, .42), 1.24, 1.06, fill=False,
                                       ec=DIM, lw=1.3, alpha=.7 * a * s))
            stick(ax, x, 1.55, 1.0, col, a * s)
            gauge_circle(ax, x, 1.55, 1.0, a * s)
            ax.annotate("", (x - .70, 1.0), (x - 1.42, 1.0),
                        arrowprops=dict(arrowstyle="-|>", color=DIM, lw=1.5, alpha=a * s))
        ax.text(x, 0.12, WHO[i], ha="center", fontsize=19, color=col, alpha=a * s)
        ax.text(x, -0.32, WHOLONG[i], ha="center", fontsize=12, color=DIM, alpha=a * s)
    b = fade(max(0, k - 215), max(1, n - 215), 0.14)
    text(fig, .5, .14, "each one carries a gauge circle of his own:", 20, DIM, b)
    text(fig, .5, .075, "the phase he cannot see around", 20, INK, b)


def sc_staircase(fig, k, n):
    a = fade(k, n, 0.08)
    text(fig, .5, .94, "Each new wire is one rung of the Cayley--Dickson ladder", 26, ACCENT, a, "bold")
    ax = fig.add_axes([.04, .14, .92, .74]); ax.set_axis_off()
    ax.set_xlim(0, 10.6); ax.set_ylim(-0.4, 5.1)
    for i in range(5):
        s = ease((k - 20 - 62 * i) / 56)
        if s <= 0:
            continue
        x0, y0 = 0.35 + 2.02 * i, 0.30 + 0.78 * i
        col = [FRIEND, WIGNER, ACCENT, DEAD, DEAD][i]
        ax.plot([x0, x0 + 1.95], [y0, y0], color=col, lw=2.6, alpha=.85 * a * s)
        if i < 4:
            ax.plot([x0 + 1.95, x0 + 1.95], [y0, y0 + 0.78],
                    color=DIM, lw=1.2, alpha=.5 * a * s)
        lab, wires, tot, base, fib, adds = RUNGS[i]
        ax.text(x0 + .08, y0 + .30, lab, fontsize=27, color=col, alpha=a * s)
        ax.text(x0 + .62, y0 + .32, wires, fontsize=14, color=DIM, alpha=a * s)
        t = ease((k - 42 - 62 * i) / 46)
        if t > 0:
            if base != "---":
                ax.text(x0 + .08, y0 - .34, "%s $\\rightarrow$ %s" % (tot, base),
                        fontsize=17, color=INK, alpha=a * t)
                ax.text(x0 + 1.12, y0 - .34, "fibre %s" % fib,
                        fontsize=13, color=DIM, alpha=a * t)
            else:
                ax.text(x0 + .08, y0 - .34, "no fibration", fontsize=17,
                        color=ACCENT if i == 3 else DEAD, alpha=a * t)
    b = fade(max(0, k - 330), max(1, n - 330), 0.12)
    text(fig, .5, .075, "three fibrations, and then the division algebras run out", 20, INK, b)


def sc_promotion(fig, k, n):
    a = fade(k, n, 0.10)
    text(fig, .5, .93, "Gauge here, interferable one rung up", 27, ACCENT, a, "bold")
    ax = fig.add_axes([.05, .20, .90, .62]); ax.set_axis_off()
    ax.set_xlim(0, 10.0); ax.set_ylim(0, 3.6)
    cols = [FRIEND, WIGNER, ACCENT]
    for i in range(3):
        x = 1.5 + 3.1 * i
        ax.add_patch(plt.Rectangle((x - .72, .50), 1.44, 1.16, fill=False,
                                   ec=DIM, lw=1.3, alpha=.65 * a))
        stick(ax, x, 1.74, 1.08, cols[i], a)
        ax.text(x, 0.16, ["$F$ : fibre $S^{1}$", "$W$ : fibre $S^{3}$",
                          "$O_{W}$ : fibre $S^{7}$"][i],
                ha="center", fontsize=15, color=cols[i], alpha=a)
    # a gauge circle detaches and is promoted into the next chart's fibre
    for i in range(2):
        p = ease((k - 45 - 110 * i) / 95)
        if p <= 0:
            continue
        x0, x1 = 1.5 + 3.1 * i, 1.5 + 3.1 * (i + 1)
        gauge_circle(ax, x0 + (x1 - x0) * p, 1.74, 1.08, a * (1 - 0.35 * p),
                     col=cols[i], lift=0.30 * np.sin(np.pi * p))
        if p > 0.05:
            ax.annotate("", (x0 + (x1 - x0) * p - .10, 2.70), (x0 + .16, 2.70),
                        arrowprops=dict(arrowstyle="-|>", color=cols[i], lw=1.4,
                                        ls=(0, (3, 3)), alpha=a * .8))
    b = fade(max(0, k - 250), max(1, n - 250), 0.12)
    text(fig, .5, .125, "what is a private phase in one chart", 20, DIM, b)
    text(fig, .5, .065, "is a recoverable fibre in the chart above it", 20, INK, b)


def sc_stop(fig, k, n):
    a = fade(k, n, 0.08)
    text(fig, .5, .94, "The fourth wire: the sedenions", 27, ACCENT, a, "bold")
    ax = fig.add_axes([.06, .30, .88, .56]); ax.set_axis_off()
    ax.set_xlim(0, 10.0); ax.set_ylim(0, 3.2)
    s0 = ease((k - 14) / 44)
    if s0 > 0:
        ax.text(2.4, 2.55, "$S^{31}\\ \\nrightarrow\\ S^{16}$", ha="center",
                fontsize=30, color=DEAD, alpha=a * s0)
        ax.text(2.4, 1.85, "the sedenions have zero divisors\nand admit no such map",
                ha="center", fontsize=15, color=DIM, alpha=a * s0)
        ax.text(2.4, 1.00, "no fourth fibration", ha="center", fontsize=21,
                color=ACCENT, alpha=a * s0)
        ax.text(2.4, 0.50, "the promotion has no fourth instance", ha="center",
                fontsize=14, color=DIM, alpha=a * s0)
    s1 = ease((k - 120) / 56)
    if s1 > 0:
        ax.plot([5.05, 5.05], [0.35, 2.95], color=DIM, lw=1.1,
                ls=(0, (4, 4)), alpha=.6 * a * s1)
        ax.text(7.6, 2.60, "$\\mathrm{Aut}(\\mathbb{S}) = G_{2}\\times S_{3}$",
                ha="center", fontsize=26, color=INK, alpha=a * s1)
        ax.text(7.6, 2.02, "identity component unchanged from $\\mathbb{O}$",
                ha="center", fontsize=14, color=DIM, alpha=a * s1)
        # the whole gain: one discrete third of a turn
        turn = ease((k - 215) / 90)
        cx, cy, R = 7.6, 1.05, 0.52
        ax.add_patch(plt.Circle((cx, cy), R, fill=False, ec=DIM, lw=1.2,
                                ls=(0, (3, 3)), alpha=.55 * a * s1))
        for j in range(3):
            th = np.radians(90 + 120 * j + 120 * turn)
            ax.scatter([cx + R * np.cos(th)], [cy + R * np.sin(th)],
                       s=130, color=[FRIEND, WIGNER, ACCENT][j], alpha=a * s1, zorder=5)
        ax.text(cx, cy - 1.00, "a third of a turn, and nothing continuous",
                ha="center", fontsize=14, color=DIM, alpha=a * s1)
    b = fade(max(0, k - 300), max(1, n - 300), 0.12)
    text(fig, .5, .18, "the entire gain is a component group,", 20, DIM, b)
    text(fig, .5, .115, "and a component group has no Lie algebra.", 20, INK, b)
    text(fig, .5, .045, "that discrete choice among three is the generation label", 19, ACCENT, b)


def sc_copies(fig, k, n):
    a = fade(k, n, 0.08)
    text(fig, .5, .94, "And thereafter, only copies", 27, ACCENT, a, "bold")
    ax = fig.add_axes([.07, .30, .86, .54]); ax.set_axis_off()
    ax.set_xlim(0, 10.0); ax.set_ylim(0, 3.0)
    dims = [0, 3, 14, 14, 14]
    names = ["$\\mathbb{C}$", "$\\mathbb{H}$", "$\\mathbb{O}$", "$\\mathbb{S}$", "$\\mathbb{T}$"]
    for i in range(5):
        s = ease((k - 16 - 34 * i) / 40)
        if s <= 0:
            continue
        x = 1.1 + 2.0 * i
        h = 0.085 * dims[i]
        col = [FRIEND, WIGNER, ACCENT, DEAD, DEAD][i]
        ax.add_patch(plt.Rectangle((x - .36, .55), .72, max(h, 0.035),
                                   color=col, alpha=.80 * a * s))
        ax.text(x, .22, names[i], ha="center", fontsize=22, color=col, alpha=a * s)
        ax.text(x, .62 + max(h, .035) + .16, str(dims[i]), ha="center",
                fontsize=19, color=INK, alpha=a * s)
    c = ease((k - 190) / 60)
    if c > 0:
        ax.plot([4.55, 9.6], [1.74, 1.74], color=ACCENT, lw=1.6,
                ls=(0, (5, 4)), alpha=a * c)
        ax.text(7.1, 2.46, "flat at $\\dim\\mathfrak{g}_{2} = 14$", ha="center",
                fontsize=17, color=ACCENT, alpha=a * c)
    text(fig, .5, .225, "$\\dim\\mathrm{Der}(A_{n})$ : the connected symmetry at each rung", 19, DIM, a)
    b = fade(max(0, k - 250), max(1, n - 250), 0.12)
    text(fig, .5, .125, "each further doubling adds one more $S_{3}$ and nothing else,", 19, DIM, b)
    text(fig, .5, .065, "and the derivation algebra is $\\mathfrak{g}_{2}$ from the octonions onward", 19, INK, b)


def sc_punch(fig, k, n):
    a = fade(k, n, 0.16)
    text(fig, .5, .74, "the increments of the tower are, in order:", 21, DIM, a)
    for i, (w, c) in enumerate([("a force", FRIEND), ("a force", WIGNER),
                                ("a label", ACCENT), ("copies", DEAD)]):
        s = fade(max(0, k - 20 - 16 * i), max(1, n - 20 - 16 * i), 0.18)
        text(fig, .20 + .20 * i, .60, w, 30, c, s, "bold")
    b = fade(max(0, k - 95), max(1, n - 95), 0.20)
    text(fig, .5, .41, "the chain is unbounded in length and bounded in type", 25, INK, b)
    text(fig, .5, .31, "the observer of Wigner is the last observer", 20, DIM, b)
    text(fig, .5, .25, "whose arrival changes what there is", 20, DIM, b)
    text(fig, .5, .10, "It from Bit via Gödel  ·  Paper 1, § Where the chain goes next", 16, DIM,
         fade(max(0, k - 130), max(1, n - 130), 0.20))


RENDER = {"chain": sc_chain, "staircase": sc_staircase, "promotion": sc_promotion,
          "stop": sc_stop, "copies": sc_copies, "punch": sc_punch}


def draw(fig, k):
    fig.clear()
    fig.patch.set_facecolor(BG)
    for name, lo, hi in BOUNDS:
        if lo <= k < hi:
            RENDER[name](fig, k - lo, hi - lo)
            break
    p = k / TOTAL
    fig.add_artist(plt.Line2D([0, p], [0.004, 0.004], color=FRIEND, lw=2.2,
                              alpha=.55, transform=fig.transFigure))


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--preview", type=int, default=None)
    args = ap.parse_args()
    fig = plt.figure(figsize=(12.8, 7.2), dpi=100)
    fig.patch.set_facecolor(BG)
    if args.preview is not None:
        draw(fig, args.preview)
        p = OUT.parent / ("tpreview_%04d.png" % args.preview)
        fig.savefig(p, facecolor=BG)
        print("wrote", p.relative_to(ROOT)); return
    OUT.parent.mkdir(parents=True, exist_ok=True)
    w = FFMpegWriter(fps=FPS, bitrate=4200, codec="libx264",
                     extra_args=["-pix_fmt", "yuv420p", "-preset", "medium"])
    print("frames %d  (%.1f s)" % (TOTAL, TOTAL / FPS))
    with w.saving(fig, str(OUT), dpi=100):
        for k in range(TOTAL):
            draw(fig, k)
            w.grab_frame(facecolor=BG)
            if k % 90 == 0:
                print("  %4d / %d" % (k, TOTAL), flush=True)
    print("wrote", OUT.relative_to(ROOT))


if __name__ == "__main__":
    main()
