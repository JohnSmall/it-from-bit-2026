"""Self-observation closure of the stabiliser fragment (2026-10-28T1500).

Checks behind sessions/relational_state_continuity_2026-10-28T1200.md,
section 9. The lamp principle, applied uniformly: the regime admits the
self-consistent fixed point of each of its transformations. Applied to the
stabiliser fragment with transitivity (no superselection: the group must
carry a stabiliser state to each admitted fixed point), what is generated?

A. The order-three derangement's fixed points (F magic states) sit at
   angle arccos(1/sqrt3) from the z axis; 2 cos(theta) = 2/sqrt3 is not an
   algebraic integer, so theta/pi is irrational (Niven): the rotation
   carrying |0> to an F state has infinite projective order. Numerical
   witness: closest projective return in n <= 10^6.
B. The order-two derangements' fixed points (H states) sit at pi/4: the
   rotation carrying |0> to an H state is T-like, of finite order 8; but
   Clifford together with it is Clifford+T, which is dense in SU(2).
   Numerical witness: distinct projective elements generated by Clifford
   and T grow past a cap, and the generated orbit of |0> approaches a
   seeded random point of the Bloch sphere arbitrarily closely as word
   length grows.
C. By contrast, closing under fixed points without transitivity stops:
   the 26-state set of 2026-10-10 is Clifford-invariant and finite
   (recomputed).

Fixed seed 20261028. No hidden state. Pure numpy.
"""
import numpy as np

SEED = 20261028
rng = np.random.default_rng(SEED)

I2 = np.eye(2, dtype=complex)
X = np.array([[0, 1], [1, 0]], dtype=complex)
Y = np.array([[0, -1j], [1j, 0]], dtype=complex)
Z = np.array([[1, 0], [0, -1]], dtype=complex)
H = np.array([[1, 1], [1, -1]], dtype=complex) / np.sqrt(2)
S = np.array([[1, 0], [0, 1j]], dtype=complex)
T = np.array([[1, 0], [0, np.exp(1j * np.pi / 4)]], dtype=complex)


def proj_equal(U, V, tol=1e-7):
    t = np.trace(U.conj().T @ V)
    return abs(abs(t) - 2) < tol


def bloch(psi):
    psi = psi / np.linalg.norm(psi)
    return np.real(np.array([psi.conj() @ P @ psi for P in (X, Y, Z)]))


def rot(axis, theta):
    n = np.asarray(axis, float)
    n = n / np.linalg.norm(n)
    return np.cos(theta / 2) * I2 - 1j * np.sin(theta / 2) * (n[0] * X + n[1] * Y + n[2] * Z)


def generate(gens, cap):
    """Projectively distinct words in the generators, breadth first, up to cap."""
    elems = [I2]
    keys = [I2]
    frontier = [I2]
    while frontier and len(elems) < cap:
        new = []
        for g in frontier:
            for h in gens:
                c = h @ g
                if not any(proj_equal(c, e) for e in keys):
                    elems.append(c)
                    keys.append(c)
                    new.append(c)
                    if len(elems) >= cap:
                        break
            if len(elems) >= cap:
                break
        frontier = new
    return elems


print("Self-observation closure of the stabiliser fragment, seed", SEED)
print("=" * 86)

# ---------------------------------------------------------------- A
theta_F = np.arccos(1 / np.sqrt(3))
RF = rot([0, 1, 0], theta_F)              # carries |0> (z) towards the F axis in the xz plane
# the rotation about y by theta_F sends z to (sin theta, 0, cos theta) = (sqrt(2/3), 0, 1/sqrt3): the same polar angle as F
psi = RF @ np.array([1, 0], dtype=complex)
best_n, best_dev = None, 10.0
U = I2.copy()
for n in range(1, 10 ** 6 + 1):
    U = RF @ U
    dev = abs(abs(np.trace(U)) - 2)
    if dev < best_dev:
        best_dev, best_n = dev, n
print(f"A. F-state polar angle theta = arccos(1/sqrt3) = {theta_F:.6f} rad = {theta_F/np.pi:.6f} pi;"
      f" 2cos(theta) = {2*np.cos(theta_F):.6f} = 2/sqrt3, root of 3x^2 - 4: not an algebraic integer, so theta/pi is irrational")
print(f"   rotation by theta about y: closest projective return in n <= 10^6 is n = {best_n}, ||tr U^n| - 2| = {best_dev:.2e} (never 0)")
print(f"   image of |0>: Bloch ({bloch(psi)[0]:+.4f}, {bloch(psi)[1]:+.4f}, {bloch(psi)[2]:+.4f}), z-component 1/sqrt3")

# ---------------------------------------------------------------- B
CAP = 3000
cliff = generate([H, S], 100)
cliffT = generate([H, S, T], CAP)
target = rng.normal(size=3)
target /= np.linalg.norm(target)
v0 = np.array([1, 0], dtype=complex)
dists = []
for L_cap in (100, 500, 1000, 2000, 3000):
    pts = np.array([bloch(g @ v0) for g in cliffT[:L_cap]])
    dists.append((L_cap, float(np.min(np.linalg.norm(pts - target, axis=1)))))
print(f"B. Clifford alone: {len(cliff)} projective elements (closed). Clifford + T: reached the cap of {CAP} distinct elements")
print("   distance from a seeded random Bloch point to the nearest orbit point of |0>, by number of elements enumerated:")
print("   " + "; ".join(f"{n}: {d:.4f}" for n, d in dists) + "  (decreasing: dense)")

# ---------------------------------------------------------------- C
def stab_states():
    out = []
    for P in (X, Y, Z):
        _, v = np.linalg.eigh(P)
        out += [v[:, 0], v[:, 1]]
    return out


def add_fixed_points(states, group):
    out = list(states)
    for g in group:
        _, v = np.linalg.eig(g)
        for k in range(2):
            s = v[:, k]
            if not any(abs(abs(s.conj() @ t)) > 1 - 1e-9 for t in out):
                out.append(s)
    return out


states = stab_states()
closed = add_fixed_points(states, cliff)
closed2 = add_fixed_points(closed, cliff)
moved = sum(1 for g in cliff for s in closed if not any(abs(abs((g @ s).conj() @ t)) > 1 - 1e-9 for t in closed))
print(f"C. fixed-point closure without transitivity: {len(states)} -> {len(closed)} -> {len(closed2)} states; Clifford images outside the set: {moved}"
      f"  (finite and invariant; transitivity is what forces the rotation of part A or B)")
print("=" * 86)
ok = (best_dev > 1e-12 and len(cliff) == 24 and len(cliffT) == CAP and dists[-1][1] < dists[0][1]
      and len(closed) == 26 and len(closed2) == 26 and moved == 0)
print("SELF-OBSERVATION CLOSURE:", "PASS" if ok else "FAIL")
