t3 = rng.uniform(0, 1, 3); c3_, s3_ = np.cos(t3), np.sin(t3)
print("    check: %.12f = %.12f" % (np.cos(t3.sum()), c3_[0]*c3_[1]*c3_[2] - c3_[0]*s3_[1]*s3_[2] - s3_[0]*c3_[1]*s3_[2] - s3_[0]*s3_[1]*c3_[2]))
