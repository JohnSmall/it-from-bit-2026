import numpy as np

rng = np.random.default_rng(20261007)


def conj(x):
    y = np.array(x, copy=True); y[1:] = -y[1:]; return y


def cd(x, y):
    n = x.size
    if n == 1:
        return x * y
    h = n // 2
    a, b, c, d = x[:h], x[h:], y[:h], y[h:]
    return np.concatenate((cd(a, c) - cd(conj(d), b), cd(d, a) + cd(b, conj(c))))


def unit(v): return v / np.linalg.norm(v)
def imag_unit():
    v = rng.standard_normal(8); v[0] = 0; return unit(v)
def assoc(x, y, z): return cd(cd(x, y), z) - cd(x, cd(y, z))
def phi(a, b, c): return a @ cd(b, c)
def vol(a, b, c):
    G = np.array([[a @ a, a @ b, a @ c], [b @ a, b @ b, b @ c], [c @ a, c @ b, c @ c]]); return np.sqrt(max(np.linalg.det(G), 0))
def u_of(t, n):
    o = np.zeros(8); o[0] = np.cos(t); return o + np.sin(t) * n
def rephi(u1, u2, u3): return cd(cd(u1, u2), u3)[0]


def quat_sub(a, b):
    """Orthonormal imaginary basis of the quaternionic subalgebra generated by imaginary units a, b."""
    b2 = unit(b - (a @ b) * a); c = cd(a, b2); return a, b2, c


