import numpy as np

rng = np.random.default_rng(20261008)
E = np.eye(4)


def conj(x):
    y = np.array(x, copy=True); y[1:] = -y[1:]; return y


def cd(x, y):
    n = x.size
    if n == 1:
        return x * y
    h = n // 2
    a, b, c, d = x[:h], x[h:], y[:h], y[h:]
    return np.concatenate((cd(a, c) - cd(conj(d), b), cd(d, a) + cd(b, conj(c))))


def unit(v): return v / np.linalg.norm(v)
def rq(): return unit(rng.standard_normal(4))
def rim(): v = rng.standard_normal(4); v[0] = 0; return unit(v)
def inv(q): return conj(q) / (q @ q)
def L(q): return np.array([cd(q, E[k]) for k in range(4)]).T     # left multiplication on H, 4x4
def R(q): return np.array([cd(E[k], q) for k in range(4)]).T     # right multiplication on H


def actF(g, q1, q2): return cd(q1, g), cd(q2, g)
def actAD(a, d, q1, q2): return cd(a, q1), cd(d, q2)


def M8(f):
    """8x8 real matrix of a real-linear map f on H^2."""
    cols = []
    for k in range(8):
        v = np.zeros(8); v[k] = 1; q1, q2 = f(v[:4], v[4:]); cols.append(np.concatenate((q1, q2)))
    return np.array(cols).T


I2 = np.eye(2); sy = np.array([[0, -1j], [1j, 0]])
print("Three Sp(1) actions on two qubits, Convention A, seed 20261008")
print("=" * 80)

# 1
e1 = 0.0
for _ in range(200):
    g, a, d = rq(), rq(), rq(); q = rq(), rq()
    e1 = max(e1, np.linalg.norm(np.concatenate(actF(g, *actAD(a, d, *q))) - np.concatenate(actAD(a, d, *actF(g, *q)))))
    e1 = max(e1, np.linalg.norm(np.concatenate(actAD(a, E[0], *actAD(E[0], d, *q))) - np.concatenate(actAD(E[0], d, *actAD(a, E[0], *q)))))
print("1. F commutes with A and D; A commutes with D:                      max err %.1e" % e1)

# 2
e2 = 0.0
for _ in range(200):
    a, d = rq(), rq(); q1, q2 = rq(), rq()
    w = cd(q2, inv(q1)); q1n, q2n = actAD(a, d, q1, q2); wn = cd(q2n, inv(q1n))
    e2 = max(e2, np.linalg.norm(wn - cd(cd(d, w), conj(a))))
print("2. isotropy on the chart w = q2 q1^-1: w -> d w conj(a):             max err %.1e" % e2)

# 3
e3a, e3b, e3c = 0.0, 0.0, 0.0
for _ in range(200):
    n = rim(); a, d = rq(), rq(); t = rng.uniform(0, 2 * np.pi)
    Ln = L(n)
    act = L(d) @ R(conj(a))                                  # w -> d w conj(a)
    conjJ = act @ Ln @ np.linalg.inv(act)                     # transported complex structure
    e3a = max(e3a, np.linalg.norm(conjJ - L(cd(cd(d, n), conj(d)))))           # D rotates n, A does nothing
    e3b = max(e3b, np.linalg.norm(R(conj(a)) @ Ln - Ln @ R(conj(a))))           # A commutes with every L_n
    u = np.cos(t) * E[0] + np.sin(t) * n                                          # U(1)_D(n)
    e3c = max(e3c, np.linalg.norm(L(u) @ Ln - Ln @ L(u)))
dev = max(np.linalg.norm(L(rq()) @ L(E[1]) - L(E[1]) @ L(rq())) for _ in range(50))
print("3. D moves L_n to L_{d n conj d} (%.1e); A fixes every L_n (%.1e); U(1)_D(n) fixes L_n (%.1e); generic d does not (%.2f)" % (e3a, e3b, e3c, dev))
print("   stabiliser of a complex structure in Spin(4) = U(1)_D x Sp(1)_A = U(2)")

# 4
Jl = M8(lambda q1, q2: (cd(E[1], q1), cd(E[1], q2)))          # left i on H^2
Jr = M8(lambda q1, q2: (cd(q1, E[1]), cd(q2, E[1])))          # right i on H^2


def comm(Mx, J): return np.linalg.norm(Mx @ J - J @ Mx)


worst = {"F|left-i": 0, "A|left-i": 0, "D|left-i": 0, "F|right-i": 0, "A|right-i": 0, "D|right-i": 0}
for _ in range(100):
    g = rq()
    MF = M8(lambda q1, q2, g=g: actF(g, q1, q2)); MA = M8(lambda q1, q2, g=g: actAD(g, E[0], q1, q2)); MD = M8(lambda q1, q2, g=g: actAD(E[0], g, q1, q2))
    for name, Mx in (("F", MF), ("A", MA), ("D", MD)):
        worst[name + "|left-i"] = max(worst[name + "|left-i"], comm(Mx, Jl)); worst[name + "|right-i"] = max(worst[name + "|right-i"], comm(Mx, Jr))
print("4. complex-linearity, max |[action, J]| over random group elements:")
print("   left-i  (standard phase):  F %.1e   A %.2f   D %.2f   -> F unitary (local SU(2) of qubit 2), isotropy not" % (worst["F|left-i"], worst["A|left-i"], worst["D|left-i"]))
print("   right-i (twistor packing): F %.2f   A %.1e   D %.1e   -> isotropy Spin(4) unitary, fibre not" % (worst["F|right-i"], worst["A|right-i"], worst["D|right-i"]))
K2 = M8(lambda q1, q2: (np.array([q1[0], q1[1], q1[2], -q1[3]]) * np.array([1, 1, 1, 1]) if False else conjb(q1), conjb(q2))) if False else None
# partial conjugation of qubit 2 in the Mosseri packing q = a + b j: (a, b) -> (a, conj b): x2 + i x3 -> x2 - i x3
def conjb(q): return np.array([q[0], q[1], q[2], -q[3]])
K2 = M8(lambda q1, q2: (conjb(q1), conjb(q2)))
